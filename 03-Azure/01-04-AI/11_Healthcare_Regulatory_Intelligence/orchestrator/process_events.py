"""Process change events from the regulatory lake with the saved agents.

For every change event the monitor wrote, and that has no briefing yet, run
citation -> impact -> briefing and store the result as a briefing that waits
for human sign-off. Nothing is approved here: approval stays with a person
(python3 -m regintel signoff).

Run from the lab folder:
    uv run python orchestrator/process_events.py --account <StorageAccountName>
"""
from __future__ import annotations

import argparse
import asyncio
import datetime as dt
import json
import sys
from pathlib import Path

ORCHESTRATOR = Path(__file__).resolve().parent
sys.path.insert(0, str(ORCHESTRATOR))
sys.path.insert(0, str(ORCHESTRATOR.parent))

from regintel.__main__ import DEFAULT_LAKE, _az  # noqa: E402
from regintel.lake import KNOWLEDGE, RAW, Lake, LakeError  # noqa: E402

from configuration import Configuration  # noqa: E402


def prompt_for(event: dict) -> str:
    return (
        "A change event arrived from Caldova's Regulatory Web and Change Monitor:\n"
        f"{json.dumps(event, indent=2)}\n\n"
        f"Work on {event['document_id']} v{event['version']} only. Retrieve it from the knowledge base, "
        "cite paragraphs exactly, identify obligations and their impact on Caldova, and finish with an "
        "executive briefing and a proposed action plan. Do not approve anything: the plan waits for human sign-off."
    )


def pending_events(lake: Lake, only: str | None = None) -> list:
    events = sorted((lake.raw / "events").glob("EVT-*.json"))
    selected = []
    for path in events:
        event = json.loads(path.read_text(encoding="utf-8"))
        if only and event["event_id"] != only:
            continue
        if not (lake.knowledge / "briefings" / f"{event['event_id']}.md").is_file():
            selected.append(event)
    return selected


def write_briefing(lake: Lake, event: dict, text: str, versions: dict, names: dict) -> Path:
    agents = ", ".join(f"{names[role]} v{versions[role]}" for role in names)
    content = (
        f"# Briefing for {event['document_id']} v{event['version']}: {event['title']}\n\n"
        "| Field | Value |\n|---|---|\n"
        "| Status | **PENDING HUMAN SIGN-OFF** |\n"
        f"| Change event | {event['event_id']} ({event['change']}) |\n"
        f"| Region | {event['region']} |\n"
        f"| Generated | {dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds')} |\n"
        f"| Agents | {agents} |\n\n"
        "Generated by AI agents. A person must review it before any action is taken.\n\n"
        f"{text.strip()}\n"
    )
    path = lake.knowledge / "briefings" / f"{event['event_id']}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return path


async def process(config: Configuration, lake: Lake, credential, only: str | None, limit: int, chain=None) -> list:
    """Run the agent chain once for each change event that has no briefing yet."""
    if chain is None:
        import workflow as chain

    events = pending_events(lake, only)[:limit]
    if not events:
        print("No change events are waiting for a briefing.")
        return []
    versions = chain.resolve_versions(config, credential)
    assistant = chain.build_workflow(config, credential, versions)
    written = []
    for event in events:
        print(f"Processing {event['event_id']} ...", flush=True)
        response = await assistant.run(prompt_for(event))
        if not response.text.strip():
            raise RuntimeError(f"The workflow returned no briefing for {event['event_id']}. Check the agent traces in Foundry.")
        written.append(write_briefing(lake, event, response.text, versions, config.names))
        print(f"  Briefing written: briefings/{event['event_id']}.md")
    return written


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--account", help="Storage account name. Omit to use only the local lake (out/lake).")
    parser.add_argument("--lake", type=Path, default=DEFAULT_LAKE)
    parser.add_argument("--event", help="Process only this event ID, for example EVT-EU-SA-2027-004-v1")
    parser.add_argument("--limit", type=int, default=3, help="Maximum events per run (default 3)")
    parser.add_argument("--starter", action="store_true", help="Use your starter/workflow.py instead of the finished workflow.py")
    args = parser.parse_args(argv)

    from azure.identity import DefaultAzureCredential, ManagedIdentityCredential
    from dotenv import load_dotenv

    chain = None
    if args.starter:
        import check_starter

        chain = check_starter.load(ORCHESTRATOR / "starter" / "workflow.py")
        problems = check_starter.check(chain)
        if problems:
            print("ERROR: starter/workflow.py is not finished yet:\n  - " + "\n  - ".join(problems)
                  + "\nRun: uv run python orchestrator/check_starter.py", file=sys.stderr)
            return 1
    load_dotenv(ORCHESTRATOR / ".env", override=False)
    lake = Lake(args.lake)
    try:
        config = Configuration.from_environment()
        if args.account:
            for container, pattern, folder in ((RAW, "events/*", lake.raw), (KNOWLEDGE, "briefings/*", lake.knowledge)):
                folder.mkdir(parents=True, exist_ok=True)
                _az("storage", "blob", "download-batch", "--account-name", args.account, "--source", container,
                    "--destination", str(folder), "--pattern", pattern, "--overwrite", "true")
        credential = ManagedIdentityCredential() if config.managed_identity else DefaultAzureCredential()
        try:
            written = asyncio.run(process(config, lake, credential, args.event, args.limit, chain))
        finally:
            credential.close()
        if args.account and written:
            _az("storage", "blob", "upload-batch", "--account-name", args.account, "--destination", KNOWLEDGE,
                "--source", str(lake.knowledge / "briefings"), "--destination-path", "briefings", "--overwrite", "true")
            print(f"Uploaded {len(written)} briefing(s) to '{KNOWLEDGE}/briefings'. Re-run the knowledge source indexer to make them searchable.")
    except (ValueError, LakeError, RuntimeError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
